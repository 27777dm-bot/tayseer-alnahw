function Router() {
  return (
    // Keep a shared shell (sidebar, navbar) outside the boundary so it
    // survives a page crash.
    <RoutedErrorBoundary>
      <Switch>
        <Route path="/" component={Home} />
        <Route path="/year/:year/lesson/:lessonIndex">
          {(params) => {
            const year = params.year as YearKey;
            const lessonIndex = Number(params.lessonIndex) - 1;
            return curricula[year] && Number.isInteger(lessonIndex) ? <LessonDetailPage year={year} lessonIndex={lessonIndex} /> : <NotFound />;
          }}
        </Route>
        <Route path="/year/:year">
          {(params) => {
            const year = params.year as YearKey;
            return curricula[year] ? <Curriculum year={year} /> : <NotFound />;
          }}
        </Route>
        <Route component={NotFound} />
      </Switch>
    </RoutedErrorBoundary>
  );
}

function RoutedErrorBoundary({ children }: { children: ReactNode }) {
  const [location] = useLocation();
  return <ErrorBoundary resetKey={location}>{children}</ErrorBoundary>;
}

function App() {
  return (
    <QueryClientProvider client={queryClient}>
      <TooltipProvider>
        <WouterRouter base={import.meta.env.BASE_URL.replace(/\/$/, '')}>
          <Router />
        </WouterRouter>
        <Toaster />
      </TooltipProvider>
    </QueryClientProvider>
  );
}

export default App;
